# 1. Create content_distributor.py
print("[1/2] Creating content_distributor.py...")

distributor_code = r'''"""Content Distributor: Analyzes AI output and saves it to DataManager sections."""
import logging
import re
from typing import Dict, Any, List, Optional
from datetime import datetime

logger = logging.getLogger(__name__)


class ContentDistributor:
    """Routes AI-generated content to appropriate project sections."""
    
    def __init__(self, data_manager):
        self.dm = data_manager
    
    def distribute(self, user_query: str, ai_response: str, category: str) -> Dict[str, Any]:
        """Analyze response and save relevant parts to DataManager.
        
        Args:
            user_query: Original user request
            ai_response: Text generated by LLM
            category: Detected topic ('strategy', 'content_plan', etc.)
            
        Returns:
            Summary of actions taken
        """
        actions_taken = []
        
        if category == "strategy":
            # Try to parse strategy document structure
            parsed_strategy = self._parse_strategy_document(ai_response)
            if parsed_strategy:
                current_strat = self.dm.get_strategy() or {}
                updated_strat = {**current_strat, **parsed_strategy}
                self.dm.update_strategy(updated_strat)
                actions_taken.append("Updated Strategy section")
                
        elif category == "content_plan":
            # Parse list of posts/topics
            items = self._parse_content_list(ai_response)
            for item in items:
                new_entry = {
                    "id": f"cp_{datetime.now().strftime('%Y%m%d%H%M%S')}_{len(items)}",
                    "date": item.get("date", ""),
                    "topic": item.get("topic", ""),
                    "format": item.get("format", "Post"),
                    "status": "Planned",
                    "source": "AI Generated"
                }
                self.dm.add_content_plan_item(new_entry)
                actions_taken.append(f"Added content plan item: {item['topic'][:30]}...")
                
        elif category == "shooting":
            # Create shooting task from description
            task_data = self._extract_shooting_task(ai_response)
            if task_data:
                created_task = self.dm.create_shooting_task(task_data)
                actions_taken.append(f"Created shooting task: {created_task['id']}")
                
        else:
            logger.info(f"No specific distributor rule for category '{category}'")
            
        return {
            "success": len(actions_taken) > 0,
            "actions": actions_taken,
            "timestamp": datetime.now().isoformat()
        }
    
    def _parse_strategy_document(self, text: str) -> Optional[Dict[str, str]]:
        """Extract key strategy blocks using regex/heuristics."""
        result = {}
        
        # Look for headers like "## Целевая аудитория" or "**Audience:**"
        patterns = {
            "about": r'(?:О проекте|About).*?\n(.*?)(?=##|\*\*|$)',
            "audience": r'(?:Целевая аудитория|Target Audience).*?\n(.*?)(?=##|\*\*|$)',
            "positioning": r'(?:Позиционирование|Positioning).*?\n(.*?)(?=##|\*\*|$)',
            "usp": r'(?:УТП|Unique Selling Proposition).*?\n(.*?)(?=##|\*\*|$)',
        }
        
        for key, pattern in patterns.items():
            match = re.search(pattern, text, re.IGNORECASE | re.DOTALL)
            if match:
                content = match.group(1).strip()
                if len(content) > 10:  # Ignore empty/tiny fragments
                    result[key] = content
                    
        return result if result else None
    
    def _parse_content_list(self, text: str) -> List[Dict[str, str]]:
        """Extract bullet points as content ideas."""
        lines = text.split('\n')
        items = []
        
        for line in lines:
            stripped = line.strip()
            # Detect list markers (- , *, • , 1. ) followed by text
            if re.match(r'^[-*•\d]+\.\s+', stripped) or stripped.startswith('-'):
                clean_text = re.sub(r'^[-*•\d]+\.\s*', '', stripped).strip()
                if len(clean_text) > 5:
                    # Simple heuristic: first sentence is Topic, rest is Description
                    sentences = re.split(r'[.!?]\s+', clean_text)
                    topic = sentences[0][:50]
                    desc = " ".join(sentences[1:])[:100]
                    
                    items.append({
                        "topic": topic,
                        "description": desc,
                        "date": ""  # Will be filled later or left blank
                    })
        
        return items
    
    def _extract_shooting_task(self, text: str) -> Optional[Dict[str, Any]]:
        """Pull location/time/type from descriptive text."""
        loc_match = re.search(r'локаци\w+:?\s*([^\n]+)', text, re.IGNORECASE)
        time_match = re.search(r'\b(\d{1,2}[.:]\d{2})\b', text)
        type_match = re.search(r'(фото|видео|съёмк\w+)', text, re.IGNORECASE)
        
        if not loc_match:
            return None
            
        return {
            "location": loc_match.group(1).strip(),
            "time": time_match.group(1) if time_match else "10:00",
            "type": type_match.group(1).capitalize() if type_match else "Фото",
            "notes": text[:200],  # Truncated summary
            "priority": "Средний"
        }
'''

